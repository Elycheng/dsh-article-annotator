/**
 * Build the browser half (`lib/client.js`).
 *
 * The DSH client module loader expects a vendor-CJS closure factory registered
 * through `window.__ModuleLoader__.load({ id, factory })` (the shape shipped by
 * dsh-better-sidebar and dsh-client-ui-quote). tsc compiles the single TSX
 * source to CommonJS with `react` left as an external `require("react")`; this
 * script wraps that output in the loader factory.
 *
 * Requirements: a TypeScript compiler (local devDependency, or `TSC_BIN`).
 * The runtime bundle itself has zero dependencies besides the platform-level
 * `react` provided by DSH.
 */
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(HERE, '..')
const OUT_DIR = join(ROOT, 'lib')
const TMP_DIR = join(OUT_DIR, '.client-build')
const TS_SOURCE = join(TMP_DIR, 'index.js')
const TARGET = join(OUT_DIR, 'client.js')
const PLUGIN_ID = 'dsh-article-annotator'

/** Candidate TypeScript compilers, in preference order. */
function tscCandidates() {
  const candidates = []
  if (typeof process.env.TSC_BIN === 'string' && process.env.TSC_BIN !== '') candidates.push(process.env.TSC_BIN)
  candidates.push(join(ROOT, 'node_modules', 'typescript', 'bin', 'tsc'))
  candidates.push(join(ROOT, '..', 'node_modules', 'typescript', 'bin', 'tsc'))
  return candidates.filter((candidate) => existsSync(candidate))
}

function compile() {
  const tsc = tscCandidates()[0]
  if (tsc === undefined) {
    throw new Error('找不到 TypeScript 编译器：请先 `npm install`，或用 TSC_BIN 指向 typescript/bin/tsc。')
  }
  const result = spawnSync(process.execPath, [tsc, '-p', join(ROOT, 'tsconfig.client.json')], { cwd: ROOT, stdio: 'inherit' })
  if (result.status !== 0) throw new Error('tsc 编译失败（exit ' + result.status + '）。')
}

function wrap(body) {
  const indented = body
    .split('\n')
    .map((line) => (line.trim() === '' ? '' : '      ' + line))
    .join('\n')
  return [
    '/**',
    ' * dsh-article-annotator — browser bundle (generated by scripts/build-client.mjs).',
    ' *',
    ' * Vendor-CJS closure factory consumed by the DSH client module loader. Only',
    ' * `react` is requested from the host module table; everything else in this',
    ' * file is the plugin itself.',
    ' */',
    'window.__ModuleLoader__.load({',
    '  id: ' + JSON.stringify(PLUGIN_ID) + ',',
    '  factory: (require) => {',
    '    var module = { exports: {} };',
    '    var exports = module.exports;',
    '    Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });',
    '    (function (module, exports, require) {',
    indented,
    '    })(module, module.exports, require);',
    '    return module.exports;',
    '  },',
    '});',
    '',
  ].join('\n')
}

async function main() {
  await mkdir(OUT_DIR, { recursive: true })
  await rm(TMP_DIR, { recursive: true, force: true })
  compile()
  const body = await readFile(TS_SOURCE, 'utf8')
  await writeFile(TARGET, wrap(body), 'utf8')
  await rm(TMP_DIR, { recursive: true, force: true })
  const bytes = Buffer.byteLength(await readFile(TARGET))
  console.log('built lib/client.js (' + (bytes / 1024).toFixed(1) + ' KiB) for id ' + PLUGIN_ID)
}

await main()
